/** @param {string} key 예: '2024-1' */
export function pastExamByKey(key) {
  return PAST_EXAMS.find((e) => e.key === key) ?? null;
}

/** 회차 표시 이름 — '2024년 1회' */
export const pastExamLabel = (e) => `${e.year}년 ${e.round}회`;

/** 코드 문항 주제의 언어 (`code:java` → 'java'), 코드 주제가 아니면 null */
export function codeLangOf(ref) {
  return typeof ref === 'string' && ref.startsWith('code:') ? ref.slice(5) : null;
}
